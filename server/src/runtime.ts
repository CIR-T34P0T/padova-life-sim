import type { ActionId, CourseId, JobId, MovingCharacter, ResolvedEffect, TargetKind, Vec2 } from "@padova/shared";

/** A shift being worked (M7). Decided by the server when the shift starts; paid only on completion. */
export interface ShiftInProgress {
  /** Server-chosen UUID; the wage's ledger key is `wage:<id>`. */
  id: string;
  jobId: JobId;
  gradeId: string;
  gradeLabel: string;
  wageCents: number;
  gameDay: number;
  startedGameMinute: number;
}

/** The one action a player is currently walking to or performing. */
export interface PendingAction {
  id: number;
  action: ActionId;
  targetKind: TargetKind;
  targetId: string;
  /** Café item for "buy". */
  itemId?: string;
  /** Idempotency id for purchases (client-supplied or generated by the server). */
  requestId: string;
  /** Seat or standing spot reserved for this action ("" for actions without one). */
  seatId: string;
  /**
   * "approach": walking to the interaction point. "paying": waiting for the
   * database (a purchase being charged, a hire or an enrolment being written,
   * a finished shift's wage being paid, a lecture or an exam being recorded).
   * "active": doing it.
   */
  phase: "approach" | "paying" | "active";
  /** Interaction point the character is walking to. */
  goal: Vec2;
  /** Server time (ms) a timed active action finishes; 0 = untimed. */
  endsAt: number;
  /** Server time (ms) the active phase began. */
  startedAt: number;
  /** Timed effect being applied (null for untimed actions). */
  effect: ResolvedEffect | null;
  /** Share (0–1) of the effect already applied; the life system tracks it. */
  appliedFraction: number;
  /** Times a greeting re-planned because the other player moved. */
  replans: number;
  /** The shift, for "work" once it has started. */
  shift?: ShiftInProgress;
  /** The lecture or exam sitting, for "attend" and "exam" once started (M8). */
  course?: CourseSlotInProgress;
}

/** Which lecture or sitting an "attend" or "exam" action counts for, fixed when it starts. */
export interface CourseSlotInProgress {
  kind: "lecture" | "exam";
  courseId: CourseId;
  /** The timetable key: a lecture ("d12-0900") or a sitting ("d13"). */
  key: string;
  gameDay: number;
}

/** Server-only data per player. Never sent to clients. */
export interface PlayerRuntime {
  /** The area the character is in (M7c): "plaza" or an indoor room's id. */
  area: string;
  character: MovingCharacter;
  intentWindowStart: number;
  intentsInWindow: number;
  pending: PendingAction | null;
  /** Last greeting time per target session id (cooldown). */
  /** When this player last greeted or chatted with another: key "<action>:<target session id>". */
  lastSocialAt: Map<string, number>;
}
